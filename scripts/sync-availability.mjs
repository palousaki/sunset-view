// Regenerates blocked-dates.js from the Airbnb calendar export (iCal).
// Run by .github/workflows/sync-availability.yml on a schedule.
import { writeFileSync } from "fs";

const ICS_URL = process.env.AIRBNB_ICS_URL;
if (!ICS_URL) {
  console.error("Missing AIRBNB_ICS_URL env var");
  process.exit(1);
}

// Airbnb calendars end with a single huge "Not available" block covering
// every date past the host's booking window - that's not a real
// reservation, so ranges longer than this are dropped.
const MAX_BLOCK_DAYS = 60;

function toIsoDate(yyyymmdd) {
  return `${yyyymmdd.slice(0, 4)}-${yyyymmdd.slice(4, 6)}-${yyyymmdd.slice(6, 8)}`;
}

function daysBetween(a, b) {
  return (new Date(b) - new Date(a)) / 86400000;
}

const res = await fetch(ICS_URL);
if (!res.ok) throw new Error(`Failed to fetch calendar: ${res.status}`);
const ics = await res.text();

const todayStr = new Date().toISOString().split("T")[0];

const ranges = [...ics.matchAll(/BEGIN:VEVENT[\s\S]*?END:VEVENT/g)]
  .map(([event]) => {
    const start = event.match(/DTSTART;VALUE=DATE:(\d{8})/)?.[1];
    const end = event.match(/DTEND;VALUE=DATE:(\d{8})/)?.[1];
    return start && end ? [toIsoDate(start), toIsoDate(end)] : null;
  })
  .filter(Boolean)
  .filter(([, end]) => end > todayStr)
  .filter(([start, end]) => daysBetween(start, end) <= MAX_BLOCK_DAYS)
  .sort(([a], [b]) => (a < b ? -1 : 1));

const body = ranges.map(([start, end]) => `  ["${start}", "${end}"],`).join("\n");

writeFileSync(
  "blocked-dates.js",
  `// Dates already booked or blocked on the Airbnb calendar.
// Auto-generated by scripts/sync-availability.mjs - do not edit by hand.
// Each range is [checkin, checkout) - checkout day itself is free.
const BLOCKED_RANGES = [
${body}
];
`
);

console.log(`Synced ${ranges.length} blocked range(s).`);
